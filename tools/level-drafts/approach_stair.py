#!/usr/bin/env python3
"""Підступ до Стража як зруйновані парадні сходи (2026-11-12, користувач: «кімнати мають бути різного типу»;
задум Claude за постійною згодою, gamedesign/LEVEL_LOOK_2.md). Переписує сітку кімнати в tomb.txt: краї, двері й отвір
лишаються, нутро — два марші сходів кладкою, без плит на ланцюгах. Потім — LevelCheck.
  .venv/bin/python tools/level-drafts/approach_stair.py
"""
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]
P = ROOT / "Assets/Game/Levels/tomb.txt"
ID = "room_tomb_guardian_approach"

t = P.read_text(encoding="utf-8")
a = t.index(f"room {ID} ")
g = t.index("grid\n", a) + 5
e = t.index("\nend", g)
rows = [list(r) for r in t[g:e].split("\n")]
H, W = len(rows), len(rows[0])
assert (W, H) == (42, 35)

# нутро — повітря (краї: колонки 0-1, 40-41, ряди 0-1, 33-34 — як були)
for y in range(2, 33):
    for x in range(2, 40):
        rows[y][x] = "."


def fill(x0, x1, y0, y1, ch="#"):
    for y in range(y0, y1 + 1):
        for x in range(x0, x1 + 1):
            rows[y][x] = ch


fill(2, 40, 0, 1)
# правий низ: блок і коридор до правих дверей (ряди 26-30)
fill(30, 34, 30, 32); fill(30, 41, 31, 32); fill(34, 39, 24, 25)
# права маса за брамою, брама (стоять на ряду 9) на консолі
fill(34, 39, 11, 23); fill(32, 39, 10, 10)
# склепіння: похило донизу ліворуч
fill(2, 10, 2, 9); fill(11, 20, 2, 6); fill(21, 30, 2, 4)
# перший марш — летючі сходи від блоку вгору ліворуч до майданчика лівих дверей
fill(25, 29, 30, 32)          # s1 — на підлозі, при блоці
fill(20, 24, 27, 27)          # s2
fill(16, 20, 24, 25)          # s3
fill(12, 16, 21, 22)          # s4
fill(2, 11, 19, 20); fill(2, 6, 21, 21); fill(11, 12, 20, 21)   # майданчик біля лівих дверей, консоль у стіні
# сходинки — одна стрічка кладки: низ кожної сходинки зростається з наступною
fill(20, 24, 28, 28); fill(19, 21, 26, 27)      # s2 товща, шов s2-s3
fill(15, 17, 23, 24)                            # шов s3-s4
# другий марш — тераси вгору праворуч до брами
fill(15, 20, 16, 16)          # t1
fill(24, 29, 13, 13)          # t2 — балкон
fill(30, 33, 16, 17)          # консоль під балконом з правої маси
# речі
rows[18][6] = "u"             # урна на майданчику
rows[12][27] = "r"            # кільце на терасі t2
rows[32][18] = "n"            # Северин під сходами
rows[32][22] = "i"            # камінь Стража під сходами

new = "\n".join("".join(r) for r in rows)
P.write_text(t[:g] + new + t[e:], encoding="utf-8")
print(new)
