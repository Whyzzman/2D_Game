#!/usr/bin/env python3
"""Takes each room's colours from its Midjourney backdrop, so the playfield's stone belongs to the painting
behind it (2026-10-28, user: «make the level look completely different, more beautiful, less raw»).

  python tools/midjourney/palettes.py tomb

Writes design/levels/painter/palette-<zone>.js: for each room with a backdrop its shadow, middle and light
colours (20–30th, 50–60th and 90–97th percentile of brightness, averaged). The painter tints the stone, its lit
rim and the props on it from these; a room without a backdrop keeps the zone's own look.
"""
import json
import sys
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[2]


def palette(path):
    image = Image.open(path).convert("RGB").resize((96, 96))
    pixels = list(image.get_flattened_data()) if hasattr(image, "get_flattened_data") else list(image.getdata())
    pixels.sort(key=lambda p: 0.3 * p[0] + 0.59 * p[1] + 0.11 * p[2])
    n = len(pixels)

    def band(lo, hi):
        part = pixels[int(n * lo): max(int(n * lo) + 1, int(n * hi))]
        return [round(sum(p[i] for p in part) / len(part)) for i in range(3)]

    return {"dark": band(0.2, 0.3), "mid": band(0.5, 0.6), "light": band(0.9, 0.97)}


def main():
    zone = sys.argv[1]
    source = ROOT / "design/levels/midjourney" / zone
    rooms = {}
    for image in sorted(source.glob("room_*.png")):
        rooms[image.stem] = palette(image)
    out = ROOT / "design/levels/painter" / f"palette-{zone}.js"
    out.write_text("// Generated by tools/midjourney/palettes.py — do not edit.\n"
                   "window.LevelPalettes = window.LevelPalettes || {};\n"
                   f"window.LevelPalettes.{zone} = {json.dumps(rooms, indent=1)};\n", encoding="utf-8", newline="\n")
    print(f"{out.relative_to(ROOT)}: {len(rooms)} rooms")


if __name__ == "__main__":
    main()
