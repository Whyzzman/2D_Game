#!/usr/bin/env python3
"""Packs a zone's seamless Midjourney textures into a script the level painter loads synchronously.

  python tools/midjourney/textures.py tomb

Reads design/levels/midjourney/<zone>/textures/*.png, keeps brightness only (8-bit grey, 512 px) and writes
design/levels/painter/textures-<zone>.js. Headless Chrome screenshots the painter before images loaded with
<img> finish decoding, so the painter never fetches the PNGs itself (gamedesign/LEVEL_TOOL.md).
"""
import base64
import sys
from pathlib import Path

from PIL import Image, ImageFilter

ROOT = Path(__file__).resolve().parents[2]
SIZE = 512


def main():
    zone = sys.argv[1]
    src = ROOT / "design/levels/midjourney" / zone / "textures"
    lines = [f"// Generated by tools/midjourney/textures.py from design/levels/midjourney/{zone}/textures — do not edit.",
             "window.LevelTextureData = window.LevelTextureData || {};",
             f"window.LevelTextureData.{zone} = {{"]
    for png in sorted(src.glob("*.png")):
        grey = Image.open(png).convert("L").resize((SIZE, SIZE), Image.LANCZOS)
        # Photo grain reads raw next to painted art: flatten it into soft painted shapes
        # (median keeps the big cracks and edges, the blur takes the speckle). Wrap-padded so the tile stays seamless.
        pad = 16
        tiled = Image.new("L", (SIZE + 2 * pad, SIZE + 2 * pad))
        for dx in (-1, 0, 1):
            for dy in (-1, 0, 1):
                tiled.paste(grey, (pad + dx * SIZE, pad + dy * SIZE))
        tiled = tiled.filter(ImageFilter.MedianFilter(9)).filter(ImageFilter.GaussianBlur(2.2))
        grey = tiled.crop((pad, pad, pad + SIZE, pad + SIZE))
        name = png.stem.split("_", 2)[-1]  # tex_tomb_rock -> rock
        lines.append(f'  {name}: {{ w: {SIZE}, h: {SIZE}, b64: "{base64.b64encode(grey.tobytes()).decode()}" }},')
    lines.append("};")
    out = ROOT / "design/levels/painter" / f"textures-{zone}.js"
    out.write_text("\n".join(lines) + "\n", encoding="utf-8", newline="\n")
    print(f"{out.relative_to(ROOT)}: {len(lines) - 4} textures")


if __name__ == "__main__":
    main()
